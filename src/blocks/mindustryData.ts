export type DropdownOption = [string, string];

const literalOptions = (values: string[]): DropdownOption[] => values.map((value) => [value, value]);

const prefixedOptions = (values: string[]): DropdownOption[] => {
  return values.map((value) => [`@${value}`, `@${value}`]);
};

const groupedPrefixedOptions = (group: string, values: string[]): DropdownOption[] => {
  return values.map((value) => [`${group} @${value}`, `@${value}`]);
};

const uniqueOptions = (options: DropdownOption[]): DropdownOption[] => {
  const seen = new Set<string>();
  return options.filter((option) => {
    if (seen.has(option[1])) {
      return false;
    }
    seen.add(option[1]);
    return true;
  });
};

